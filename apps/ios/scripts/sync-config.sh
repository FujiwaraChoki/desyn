#!/usr/bin/env bash
# Writes apps/ios/Config/Endpoints.xcconfig from deploy/env/public.env (the hosted Convex Cloud deployment and
# the web app), so the iOS build talks to the same backend as the web. `--check` fails when the file is stale.
# xcconfig treats "//" as a comment, so URLs are written as https:/$()/host.
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "${here}/../../.." && pwd)"
env_file="${root}/deploy/env/public.env"
out="${here}/../Config/Endpoints.xcconfig"

value() {
  sed -n "s/^$1=//p" "${env_file}" | head -n 1
}

escape() {
  # The literal "$()" is the xcconfig escape that keeps "//" from starting a comment.
  # shellcheck disable=SC2016
  printf '%s' "$1" | sed 's|://|:/$()/|'
}

convex_url="$(value NEXT_PUBLIC_CONVEX_URL)"
site_url="$(value NEXT_PUBLIC_CONVEX_SITE_URL)"
app_url="$(value APP_URL)"
if [ -z "${convex_url}" ] || [ -z "${site_url}" ] || [ -z "${app_url}" ]; then
  echo "deploy/env/public.env lacks NEXT_PUBLIC_CONVEX_URL, NEXT_PUBLIC_CONVEX_SITE_URL or APP_URL" >&2
  exit 1
fi
app_host="$(printf '%s' "${app_url}" | sed -E 's|^[a-z]+://||; s|/.*$||')"

content="// Generated by apps/ios/scripts/sync-config.sh from deploy/env/public.env. Do not edit by hand.
DESYN_CONVEX_URL = $(escape "${convex_url}")
DESYN_CONVEX_SITE_URL = $(escape "${site_url}")
DESYN_APP_URL = $(escape "${app_url}")
DESYN_APP_HOST = ${app_host}
"

if [ "${1:-}" = "--check" ]; then
  if [ ! -f "${out}" ] || [ "$(cat "${out}")" != "$(printf '%s' "${content}")" ]; then
    echo "Config/Endpoints.xcconfig is stale; run apps/ios/scripts/sync-config.sh" >&2
    exit 1
  fi
  echo "Config/Endpoints.xcconfig is up to date"
else
  printf '%s' "${content}" > "${out}"
  echo "wrote ${out}"
fi
