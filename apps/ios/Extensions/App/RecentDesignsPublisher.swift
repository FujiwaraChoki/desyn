/// Keeps the widget's snapshot (App Group container) in step with the library: the signed-in person's most recent
/// designs with small thumbnails, written when the app becomes active or goes to the background, when an editor
/// closes, and cleared on sign-out so nothing of a previous account stays on the home screen.
@MainActor
final class RecentDesignsPublisher {
    static let shared = RecentDesignsPublisher()

    private let store = RecentDesignsStore.shared()
    private var running: Task<Void, Never>?
    private let session: URLSession = {
        let configuration = URLSessionConfiguration.default
        configuration.timeoutIntervalForRequest = 20
        return URLSession(configuration: configuration)
    }()

    func refresh(_ app: AppModel) {
        running?.cancel()
        running = Task { [weak self] in await self?.publish(app.session) }
    }

    private func publish(_ session: AppSession) async {
        let appURL = session.environment.appURL
        guard session.phase == .signedIn else {
            if session.phase == .signedOut {
                store.clear(appURL: appURL)
                WidgetCenter.shared.reloadAllTimelines()
            }
            return
        }
        guard let workspaceId = session.workspaceId ?? session.currentWorkspace?.id,
              let page = try? await session.api.designs(workspaceId: workspaceId, filter: .recent, pageSize: 8)
        else { return }
        var designs: [RecentDesign] = []
        for summary in page.page where summary.state != "trashed" && summary.state != "creating" {
            if Task.isCancelled { return }
            let updated = Date(timeIntervalSince1970: summary.updatedAt / 1000)
            let file = RecentDesignsStore.thumbnailFileName(designId: summary.id, version: updated)
            var thumbnail: String?
            if store.hasThumbnail(file) {
                thumbnail = file
            } else if let url = summary.thumbnailUrl.flatMap(URL.init(string:)), let data = await thumbnailData(url) {
                try? store.writeThumbnail(data, file: file)
                thumbnail = file
            }
            designs.append(RecentDesign(
                id: summary.id,
                name: summary.name,
                kind: summary.kind,
                kindLabel: summary.designKind.label,
                width: summary.width,
                height: summary.height,
                pageCount: Int(summary.pageCount),
                updatedAt: updated,
                thumbnailFile: thumbnail
            ))
        }
        let firstName = session.profile?.firstName
        try? store.save(RecentDesignsSnapshot(ownerName: firstName, signedIn: true, designs: designs, appURL: appURL))
        WidgetCenter.shared.reloadAllTimelines()
        // "Open <design> in Desyn" phrases list the recent designs.
        DesynShortcuts.updateAppShortcutParameters()
    }

    /// A small JPEG of the thumbnail (widgets have a tight memory budget).
    private func thumbnailData(_ url: URL) async -> Data? {
        guard let result = try? await session.data(from: url) else { return nil }
        let (data, response) = result
        guard (response as? HTTPURLResponse).map({ (200..<300).contains($0.statusCode) }) ?? true,
              let source = CGImageSourceCreateWithData(data as CFData, nil)
        else { return nil }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: 480,
        ]
        guard let image = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return nil }
        return UIImage(cgImage: image).jpegData(compressionQuality: 0.82)
    }
}

/// Wires the suite into the app's root view: widget snapshot refreshes and sign-out cleanup.
struct DesynSuiteModifier: ViewModifier {
    let app: AppModel
    @Environment(\.scenePhase) private var scenePhase

    func body(content: Content) -> some View {
        content
            .onChange(of: scenePhase) { _, phase in
                if phase == .background || phase == .active { RecentDesignsPublisher.shared.refresh(app) }
            }
            .onChange(of: app.session.phase) { _, _ in
                RecentDesignsPublisher.shared.refresh(app)
            }
            .onChange(of: app.openDesign) { _, route in
                // An editor closed: its thumbnail is regenerated by the server shortly after the last change.
                if route == nil {
                    Task {
                        try? await Task.sleep(for: .seconds(25))
                        RecentDesignsPublisher.shared.refresh(app)
                    }
                }
            }
    }
}

extension View {
    /// Installs the editor features' app-level behavior (call on the root view).
    func desynSuite(_ app: AppModel) -> some View {
        modifier(DesynSuiteModifier(app: app))
    }
}
