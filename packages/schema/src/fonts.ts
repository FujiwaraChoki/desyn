// Curated Google Fonts catalog (metadata only, no font files) and heading/body pairings. Clients load the font
// files themselves (self-hosted OFL set or on demand); the AI uses categories, tags and pairings to choose type.

export type FontCategory = "sans-serif" | "serif" | "display" | "handwriting" | "monospace";

export interface FontAxis {
  /** OpenType axis tag, e.g. "wght", "wdth", "opsz", "ital", "slnt", "SOFT". */
  tag: string;
  min: number;
  max: number;
}

export interface FontFamilyInfo {
  family: string;
  category: FontCategory;
  /** Named weights available (for variable fonts, the 100-steps within the wght axis). */
  weights: number[];
  italic: boolean;
  /** Present for variable fonts. */
  axes?: FontAxis[];
  /** Families that pair well with this one (all present in FONT_CATALOG). */
  pairsWith: string[];
  /** Mood / usage tags. */
  tags: string[];
}

