function parseWeights(spec: string): number[] {
  const range = /^(\d+)\.\.(\d+)$/.exec(spec);
  if (range) {
    const lo = Number(range[1]);
    const hi = Number(range[2]);
    const out: number[] = [];
    for (let w = lo; w <= hi; w += 100) out.push(w);
    return out;
  }
  return spec.split(",").map(Number);
}

function parseAxes(spec: string): FontAxis[] | undefined {
  if (!spec) return undefined;
  return spec.split(",").map((part) => {
    const [tag = "", min = "0", max = "0"] = part.split(":");
    return { tag, min: Number(min), max: Number(max) };
  });
}

export const FONT_CATALOG: readonly FontFamilyInfo[] = ROWS.map(
  ([family, category, weights, italic, axes, pairsWith, tags]) => {
    const info: FontFamilyInfo = {
      family,
      category,
      weights: parseWeights(weights),
      italic,
      pairsWith,
      tags,
    };
    const parsed = parseAxes(axes);
    if (parsed) info.axes = parsed;
    return info;
  },
);

const byFamily = new Map(FONT_CATALOG.map((f) => [f.family.toLowerCase(), f]));

export function getFont(family: string): FontFamilyInfo | undefined {
  return byFamily.get(family.toLowerCase());
}

export function fontsByCategory(category: FontCategory): FontFamilyInfo[] {
  return FONT_CATALOG.filter((f) => f.category === category);
}

export function isVariableFont(family: string): boolean {
  return getFont(family)?.axes !== undefined;
}

/** The available weight closest to `weight` (ties resolve to the heavier weight, as CSS matching does above 500). */
export function nearestWeight(family: string, weight: number): number {
  const weights = getFont(family)?.weights ?? [400, 700];
  const axis = getFont(family)?.axes?.find((a) => a.tag === "wght");
  if (axis) return Math.min(axis.max, Math.max(axis.min, weight));
  return weights.reduce((best, w) => {
    const d = Math.abs(w - weight);
    const bd = Math.abs(best - weight);
    return d < bd || (d === bd && w > best) ? w : best;
  });
}

