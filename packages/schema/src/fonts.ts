/** Pairings whose moods include every requested mood (case-insensitive). */
export function pairingsForMood(...moods: string[]): FontPairing[] {
  const wanted = moods.map((m) => m.toLowerCase());
  return FONT_PAIRINGS.filter((p) => wanted.every((m) => p.moods.includes(m)));
}

/** Pairings recommended for a design kind. */
export function pairingsForKind(kind: string): FontPairing[] {
  return FONT_PAIRINGS.filter((p) => p.goodFor.includes(kind));
}
