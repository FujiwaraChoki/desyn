#!/usr/bin/env python3
"""Push the Convex Cloud function environment for the hosted edition. Values are never printed.

Usage:  python3 deploy/scripts/convex-cloud-env.py prod|dev [--dry-run]

Sources, in order (later wins): deploy/env/public.env (public ids), .env (OPENROUTER_API_KEY, FAL_AI_API_KEY),
.env.keys (the owner's pasted keys). Missing generated secrets (Better Auth, BYOK encryption, render worker) are
created once per target and appended to .env.keys as <NAME>_PROD / <NAME>_DEV, so redeploys keep them stable.
The assembled file is written 0600 to a temp dir, pushed with `npx convex env set --from-file --force`, then deleted.
--dry-run prints only the variable names that would be set.
"""

from __future__ import annotations

import os
import re
import secrets
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEPLOYMENTS = {"prod": "prod:opulent-alpaca-530", "dev": "dev:unique-hedgehog-677"}
GENERATED = ("BETTER_AUTH_SECRET", "AI_KEY_ENCRYPTION_SECRET", "RENDER_WORKER_SECRET", "TEMPLATES_PIPELINE_SECRET")
PASSTHROUGH = (
    "OPENROUTER_API_KEY", "FAL_AI_API_KEY",
    "ANTHROPIC_API_KEY", "OPENAI_API_KEY", "GOOGLE_GENERATIVE_AI_API_KEY",
    "AWS_ACCESS_KEY_ID", "AWS_SECRET_ACCESS_KEY", "AWS_REGION",
    "STRIPE_SECRET_KEY", "STRIPE_WEBHOOK_SECRET", "STRIPE_PRICE_PRO_MONTHLY", "STRIPE_PRICE_PRO_YEARLY",
    "UNSPLASH_ACCESS_KEY", "PEXELS_API_KEY",
    "GOOGLE_CLIENT_ID", "GOOGLE_CLIENT_SECRET", "GITHUB_CLIENT_ID", "GITHUB_CLIENT_SECRET",
    "AXIOM_TOKEN", "AXIOM_DATASET", "AXIOM_ORG_ID",
    "ADMIN_EMAILS",
)
LINE = re.compile(r"^([A-Z][A-Z0-9_]*)=(.*)$")


def read_env(path: Path) -> dict[str, str]:
    out: dict[str, str] = {}
    if not path.exists():
        return out
    for raw in path.read_text().splitlines():
        m = LINE.match(raw.strip())
        if m:
            value = m.group(2).strip()
            if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
                value = value[1:-1]
            out[m.group(1)] = value
    return out


def ensure_generated(keys_path: Path, keys: dict[str, str], suffix: str) -> dict[str, str]:
    added = []
    for name in GENERATED:
        stored = f"{name}_{suffix}"
        if not keys.get(stored):
            keys[stored] = secrets.token_hex(32)
            added.append(f"{stored}={keys[stored]}")
    if added:
        text = keys_path.read_text()
        keys_path.write_text(text.rstrip("\n") + "\n# generated by deploy/scripts/convex-cloud-env.py\n" + "\n".join(added) + "\n")
        print(f"generated: {', '.join(a.split('=')[0] for a in added)}")
    return {name: keys[f"{name}_{suffix}"] for name in GENERATED}


def main() -> int:
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    dry = "--dry-run" in sys.argv
    if len(args) != 1 or args[0] not in DEPLOYMENTS:
        print(__doc__)
        return 2
    target = args[0]
    keys_path = ROOT / ".env.keys"
    public = read_env(ROOT / "deploy/env/public.env")
    dotenv = read_env(ROOT / ".env")
    keys = read_env(keys_path)
    merged = {**public, **dotenv, **keys}

    env: dict[str, str] = {
        "DESYN_EDITION": "hosted",
        "MAIL_TRANSPORT": "ses",
        "SES_FROM": "Desyn <hello@desyn.app>",
        "SES_CONFIGURATION_SET": "desyn",
        "POSTHOG_HOST": public.get("NEXT_PUBLIC_POSTHOG_HOST", "https://eu.i.posthog.com"),
        "POSTHOG_PROJECT_API_KEY": public.get("NEXT_PUBLIC_POSTHOG_KEY", ""),
        "LOG_LEVEL": "info" if target == "prod" else "debug",
        "S3_FORCE_PATH_STYLE": "false",
    }
    if target == "prod":
        env |= {
            "SITE_URL": "https://desyn.app",
            "APP_URL": "https://app.desyn.app",
            "AUTH_TRUSTED_ORIGINS": "https://desyn.app,https://www.desyn.app,https://docs.desyn.app",
            "S3_BUCKET": "desyn-prod-assets",
            "RENDER_WORKER_URL": "https://render.desyn.app",
        }
    else:
        env |= {
            "SITE_URL": "http://localhost:4102",
            "APP_URL": "http://localhost:4100",
            "AUTH_TRUSTED_ORIGINS": "http://localhost:4100,http://127.0.0.1:4100,http://localhost:4102,http://localhost:4103",
            "S3_BUCKET": "desyn-dev-assets",
            "RENDER_WORKER_URL": "",
        }
    for name in PASSTHROUGH:
        if merged.get(name):
            env[name] = merged[name]
    if dry:
        print(f"[{target}] would set: {', '.join(sorted(k for k, v in env.items() if v))}")
        return 0
    env |= ensure_generated(keys_path, keys, target.upper())

    payload = "".join(f"{k}={v}\n" for k, v in sorted(env.items()) if v)
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "convex.env"
        path.touch(mode=0o600)
        path.write_text(payload)
        (Path(tmp) / "package.json").write_text('{"name":"desyn-env","private":true,"dependencies":{"convex":"1.47.0"}}\n')
        proc = subprocess.run(
            ["npx", "-y", "convex@1.47.0", "env", "set", "--from-file", str(path), "--force"],
            cwd=tmp,
            env={**os.environ, "CONVEX_DEPLOYMENT": DEPLOYMENTS[target]},
            stdin=subprocess.DEVNULL,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.PIPE,
            text=True,
        )
    if proc.returncode != 0:
        # The CLI error never echoes values, but trim it anyway.
        print(f"convex env set failed ({proc.returncode}): {proc.stderr.strip()[-600:]}", file=sys.stderr)
        return 1
    print(f"[{target}] set {payload.count(chr(10))} variables on {DEPLOYMENTS[target]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
