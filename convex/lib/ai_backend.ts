export interface EventSinkOptions {
  /** Persists a batch; returns whether the run must stop (cancelled / stale chunk). */
  push(events: StoredEvent[]): Promise<{ stop: boolean }>;
  /** Stores preview bytes; returns a storage id the event references. */
  storePreview(bytes: Uint8Array, mime: string): Promise<string>;
  onStop(): void;
  /** Drop these event types (e.g. "start" on continuation chunks). */
  skip?: (event: AgentEvent) => boolean;
  flushMs?: number;
  maxBatch?: number;
}

/** Longest text / thinking event kept as one merged entry (stored strings are clipped beyond this). */
const MERGE_MAX_CHARS = 3_500;

/** A pending log entry; previews hold their slot (stream order) until their bytes are stored. */
interface PendingEvent {
  event: StoredEvent | null;
}

/**
 * Batches streamed events into few mutations: consecutive text / thinking deltas merge into one event, a
 * batch is written every `flushMs` or `maxBatch` events, previews are uploaded and stored by reference.
 * Writes are serialized and a preview keeps its place while its upload runs, so the log order matches the
 * stream order.
 */
export class EventSink {
  private pending: PendingEvent[] = [];
  private chain: Promise<void> = Promise.resolve();
  private timer: ReturnType<typeof setTimeout> | null = null;
  private stopped = false;
  error: unknown = null;

  constructor(private readonly options: EventSinkOptions) {}

  push(event: AgentEvent): void {
    if (this.options.skip?.(event)) return;
    if (event.type === "preview") {
      const { bytes, ...rest } = event;
      const slot: PendingEvent = { event: null };
      this.pending.push(slot);
      this.enqueue(async () => {
        try {
          const previewId = await this.options.storePreview(bytes, event.mime);
          slot.event = storedEvent({ ...rest, previewId });
        } catch (err) {
          // A preview that could not be stored is dropped; the rest of the log keeps flowing.
          slot.event = storedEvent({ type: "progress", label: "Preview unavailable" });
          throw err;
        }
      });
      this.schedule(true);
      return;
    }
    const last = this.pending[this.pending.length - 1]?.event;
    if (last && (event.type === "text" || event.type === "thinking") && last.type === event.type) {
      const prev = JSON.parse(last.payload) as { text: string };
      if (prev.text.length + event.text.length <= MERGE_MAX_CHARS) {
        (this.pending[this.pending.length - 1] as PendingEvent).event = storedEvent(
          { type: event.type, text: prev.text + event.text },
          last.ts,
        );
        this.schedule(false);
        return;
      }
    }
    this.pending.push({ event: storedEvent(event as unknown as { type: string }) });
    // Step boundaries flush at once: the write doubles as the cancellation check between steps.
    this.schedule(
      this.pending.length >= (this.options.maxBatch ?? 25) ||
        event.type === "done" ||
        event.type === "step",
    );
  }

  private enqueue(task: () => Promise<void>): void {
    this.chain = this.chain.then(task).catch((err) => {
      this.error ??= err;
    });
  }

  private schedule(now: boolean): void {
    if (now) {
      if (this.timer) clearTimeout(this.timer);
      this.timer = null;
      this.enqueue(() => this.write());
      return;
    }
    if (this.timer) return;
    this.timer = setTimeout(() => {
      this.timer = null;
      this.enqueue(() => this.write());
    }, this.options.flushMs ?? 400);
  }

  private async write(): Promise<void> {
    // Everything before the first preview still uploading (that one and later events wait for the next write).
    let ready = this.pending.findIndex((p) => p.event === null);
    if (ready < 0) ready = this.pending.length;
    const batch = this.pending.splice(0, ready).map((p) => p.event as StoredEvent);
    const res = await this.options.push(batch);
    if (res.stop && !this.stopped) {
      this.stopped = true;
      this.options.onStop();
    }
  }

  /** Heartbeat: renews the lease and polls for cancellation even when nothing streams. */
  poll(): void {
    this.enqueue(() => this.write());
  }

  async flush(): Promise<void> {
    if (this.timer) clearTimeout(this.timer);
    this.timer = null;
    this.enqueue(() => this.write());
    await this.chain;
  }
}
