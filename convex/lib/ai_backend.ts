/** JSON with binary parts (images in tool results) kept as base64. */
export function serializeMessages(messages: ModelMessage[]): string {
  return JSON.stringify(messages, (_key, value) => {
    if (value instanceof Uint8Array) return { __u8: Buffer.from(value).toString("base64") };
    if (value instanceof ArrayBuffer) return { __u8: Buffer.from(value).toString("base64") };
    if (value instanceof URL) return value.href;
    return value;
  });
}

export function deserializeMessages(json: string): ModelMessage[] {
  return JSON.parse(json, (_key, value) => {
    if (value && typeof value === "object" && typeof value.__u8 === "string") {
      return new Uint8Array(Buffer.from(value.__u8, "base64"));
    }
    return value;
  }) as ModelMessage[];
}

export async function loadHistory(
  ctx: ActionCtx,
  id: Id<"_storage"> | null,
): Promise<ModelMessage[]> {
  if (!id) return [];
  const blob = await ctx.storage.get(id);
  if (!blob) return [];
  return deserializeMessages(await blob.text());
}

export async function saveHistory(
  ctx: ActionCtx,
  messages: ModelMessage[],
): Promise<Id<"_storage">> {
  return await ctx.storage.store(
    new Blob([serializeMessages(messages)], { type: "application/json" }),
  );
}

/**
 * Tool calls without a result (ask_user pauses the loop before a result exists) get one so the conversation
 * stays valid for every provider: the user's answer for ask_user, a "not run" note for anything else.
 */
export function closeOpenToolCalls(
  messages: ModelMessage[],
  answer: string | null,
): ModelMessage[] {
  const answered = new Set<string>();
  for (const m of messages) {
    if (m.role !== "tool") continue;
    for (const part of m.content) if (part.type === "tool-result") answered.add(part.toolCallId);
  }
  const open: { toolCallId: string; toolName: string }[] = [];
  for (const m of messages) {
    if (m.role !== "assistant" || typeof m.content === "string") continue;
    for (const part of m.content) {
      if (part.type === "tool-call" && !answered.has(part.toolCallId)) {
        open.push({ toolCallId: part.toolCallId, toolName: part.toolName });
      }
    }
  }
  if (open.length === 0) return messages;
  return [
    ...messages,
    {
      role: "tool",
      content: open.map((call) => ({
        type: "tool-result" as const,
        toolCallId: call.toolCallId,
        toolName: call.toolName,
        output:
          call.toolName === "ask_user" && answer !== null
            ? { type: "json" as const, value: { answer } }
            : { type: "text" as const, value: "Not run: the run was paused before this call." },
      })),
    },
  ];
}

/** Id of the pending ask_user call in a run's new messages. */
export function askUserCallId(messages: ModelMessage[]): string | undefined {
  for (let i = messages.length - 1; i >= 0; i--) {
    const m = messages[i];
    if (m?.role !== "assistant" || typeof m.content === "string") continue;
    for (const part of m.content) {
      if (part.type === "tool-call" && part.toolName === "ask_user") return part.toolCallId;
    }
  }
  return undefined;
}

