export interface BackendScope {
  designId: Id<"designs">;
  userId: string;
  workspaceId: Id<"workspaces">;
  runId?: Id<"aiRuns">;
}

/** Where generated assets are stored and attributed. */
export interface AssetScope {
  userId: string;
  workspaceId: Id<"workspaces">;
  designId?: Id<"designs">;
  runId?: Id<"aiRuns">;
}

export function convexHostBackend(ctx: ActionCtx, scope: BackendScope): HostBackend {
  const cfg = workerConfig();
  return {
    async load() {
      const m = await materializeDesign(ctx, scope.designId, { decode: decompressToString });
      if (!m) throw new Error("The design is no longer available.");
      return { design: m.design, seq: m.seq };
    },
    async opsAfter(seq) {
      const out = await ctx.runQuery(internal.ai.internal.opsAfter, {
        designId: scope.designId,
        after: seq,
      });
      return {
        gap: out.gap,
        txs: out.txs.map((r: { seq: number; tx: string }) => ({
          seq: r.seq,
          tx: JSON.parse(r.tx) as Transaction,
        })),
      };
    },
    async commit(tx): Promise<HostCommitResult> {
      return await ctx.runMutation(internal.designs.designs.commitAs, {
        designId: scope.designId,
        userId: scope.userId,
        tx: JSON.stringify(tx),
      });
    },
    async assetUrls() {
      return await ctx.runQuery(internal.designs.internal.assetUrls, { designId: scope.designId });
    },
    async ingest(bytes, mime, meta) {
      return await ingestAsset(ctx, scope, bytes, mime, meta, "agent");
    },
    async fetchBytes(url) {
      // Signed URLs of our own storage: no SSRF guard needed (and self-hosted S3 is often private).
      const res = await fetch(url);
      if (!res.ok) throw new Error(`Could not read the asset (${res.status}).`);
      return {
        bytes: new Uint8Array(await res.arrayBuffer()),
        mime: res.headers.get("content-type")?.split(";")[0]?.trim() ?? "application/octet-stream",
      };
    },
    worker: cfg
      ? { call: (path, body) => callWorker(path, body, { gzip, timeoutMs: 120_000 }) }
      : null,
  };
}

function exactBuffer(bytes: Uint8Array): ArrayBuffer {
  return bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength) as ArrayBuffer;
}

/** Stores generated bytes as a workspace asset (S3 via the assets owner) and records its provenance. */
export async function ingestAsset(
  ctx: ActionCtx,
  scope: AssetScope,
  bytes: Uint8Array,
  mime: string,
  meta: AssetUploadMeta,
  task: string,
  extra: {
    costCredits?: number;
    billing?: "platform" | "byok" | "local";
    sources?: Id<"assets">[];
  } = {},
): Promise<AssetRef & { assetId: Id<"assets"> }> {
  const source = meta.source ?? (meta.ai ? "ai" : "upload");
  const stored = await ctx.runAction(internal.assets.assets.ingest, {
    workspaceId: scope.workspaceId,
    userId: scope.userId,
    name: meta.name ?? (meta.ai ? "Generated asset" : "Asset"),
    mime,
    data: exactBuffer(bytes),
    source,
    ...(meta.kind === "lottie" || meta.kind === "data" ? { declaredKind: meta.kind } : {}),
    ...(meta.ai
      ? {
          ai: {
            provider: meta.ai.provider,
            model: meta.ai.model,
            prompt: preview(meta.ai.prompt, 2000),
            ...(meta.ai.seed !== undefined ? { seed: meta.ai.seed } : {}),
          },
        }
      : {}),
    ...(meta.attribution ? { attribution: meta.attribution } : {}),
  });
  if (meta.ai) {
    await ctx.runMutation(internal.ai.internal.recordAsset, {
      assetId: stored.assetId,
      refId: stored.refId,
      workspaceId: scope.workspaceId,
      userId: scope.userId,
      ...(scope.designId ? { designId: scope.designId } : {}),
      ...(scope.runId ? { runId: scope.runId } : {}),
      task,
      provider: meta.ai.provider,
      model: meta.ai.model,
      prompt: meta.ai.prompt,
      ...(meta.ai.seed !== undefined ? { seed: meta.ai.seed } : {}),
      ...(extra.sources?.length ? { sourceAssetIds: extra.sources } : {}),
      billing: extra.billing ?? "platform",
      costCredits: extra.costCredits ?? 0,
    });
  }
  const kind: AssetRef["kind"] =
    meta.kind ??
    (mime === "image/svg+xml"
      ? "svg"
      : mime.startsWith("video/")
        ? "video"
        : mime.startsWith("audio/")
          ? "audio"
          : "image");
  return {
    assetId: stored.assetId,
    id: stored.refId,
    kind,
    mime,
    storageKey: stored.storageKey,
    bytes: bytes.byteLength,
    ...(stored.width !== null
      ? { width: stored.width }
      : meta.width
        ? { width: Math.round(meta.width) }
        : {}),
    ...(stored.height !== null
      ? { height: stored.height }
      : meta.height
        ? { height: Math.round(meta.height) }
        : {}),
    ...(meta.durationMs ? { durationMs: meta.durationMs } : {}),
    ...(meta.name ? { name: meta.name } : {}),
    source,
    ...(meta.ai ? { ai: { ...meta.ai, prompt: preview(meta.ai.prompt, 2000) } } : {}),
    ...(meta.attribution ? { attribution: meta.attribution } : {}),
  };
}

/** Stock photos (Unsplash / Pexels server keys), Iconify icons and the template library. */
export function searchProviders(
  ctx: ActionCtx,
  userId: string,
  fetchImpl: FetchLike,
): SearchProviders {
  const stock = stockFromEnv(process.env as Record<string, string | undefined>, {
    fetch: fetchImpl,
  });
  const templates: TemplateProvider = {
    async search(query, options = {}) {
      return await ctx.runQuery(internal.ai.tools.searchTemplates, {
        userId,
        query,
        ...(options.kind ? { kind: options.kind } : {}),
        limit: options.limit ?? 8,
      });
    },
    async get(id) {
      const json = await ctx.runQuery(internal.ai.tools.templateDesign, { userId, templateId: id });
      if (!json) throw new Error("Template not found.");
      return JSON.parse(json) as Design;
    },
  };
  return {
    ...(stock ? { stock } : {}),
    icons: createIconify({ fetch: fetchImpl }),
    templates,
  };
}

